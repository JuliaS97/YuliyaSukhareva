public class task2 {
    public static void main(String[] args) {

        int x = 36, y = 6;

        System.out.println(x + y);   // 42  (36 + 6)
        System.out.println(x - y);   // 30  (36 - 6)
        System.out.println(x * y);   // 216 (36 * 6)
        System.out.println(x / y);   // 6   (36 / 6)
        System.out.println(x % y);   // 0   (36 % 6 = 0, tam bolunur!)
    }
}